#Requires -Version 5.1
<#
.SYNOPSIS
    Writes a Windows Sandbox .wsb that runs the round-trip test automatically.

.DESCRIPTION
    Windows Sandbox is the quickest way to get a disposable Windows 11 machine without an ISO or a
    reboot cycle for every test run. This script generates a .wsb next to the results folder, with
    the repository mapped in (read/write, so the report survives the sandbox) and a logon command
    that runs tests\vm\Run-RoundTripTest.bat.

    Requires the "Windows Sandbox" optional feature:
      Enable-WindowsOptionalFeature -Online -FeatureName Containers-DisposableClientVM -All
    followed by a reboot. This script only writes files - it does not enable anything.

.PARAMETER RepoRoot
    Repository root. Defaults to two levels above this script.

.PARAMETER SandboxMountPath
    Where the repository appears inside the sandbox. Defaults to C:\Win11VM-ServerOptimizer.

.PARAMETER ResultsRoot
    Host folder for the .wsb and for the run's output. Defaults to <repo>\artifacts\sandbox.

.EXAMPLE
    .\New-SandboxConfig.ps1
#>

[CmdletBinding()]
param(
    [string]$RepoRoot = '',
    [string]$SandboxMountPath = 'C:\Win11VM-ServerOptimizer',
    [string]$ResultsRoot = ''
)

$ErrorActionPreference = 'Stop'

if (-not $RepoRoot) {
    $RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
}
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path

if (-not $ResultsRoot) {
    $ResultsRoot = Join-Path $RepoRoot 'artifacts\sandbox'
}
if (-not (Test-Path -LiteralPath $ResultsRoot)) {
    New-Item -ItemType Directory -Path $ResultsRoot -Force | Out-Null
}

$launcher = Join-Path $RepoRoot 'tests\vm\Run-RoundTripTest.bat'
$harness = Join-Path $RepoRoot 'tests\vm\Invoke-RoundTripTest.ps1'
foreach ($required in @($launcher, $harness)) {
    if (-not (Test-Path -LiteralPath $required)) {
        throw "Missing '$required' - run this from a complete checkout."
    }
}

# Report whether the sandbox feature is actually available. Reading the feature state does not
# require elevation; enabling it does, and that is deliberately the operator's decision.
$featureState = 'Unknown'
try {
    $feature = Get-CimInstance -Namespace root\cimv2 -ClassName Win32_OptionalFeature -Filter "Name='Containers-DisposableClientVM'" -ErrorAction Stop
    if ($feature) {
        switch ($feature.InstallState) {
            1 { $featureState = 'Enabled' }
            2 { $featureState = 'Disabled' }
            3 { $featureState = 'Absent' }
            default { $featureState = "Unknown ($($feature.InstallState))" }
        }
    }
} catch {
    Write-Verbose "Could not read the Windows Sandbox feature state: $($_.Exception.Message)"
}

$timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$sandboxOutput = Join-Path $SandboxMountPath ("artifacts\sandbox-" + $timestamp)
$wsbPath = Join-Path $ResultsRoot ("roundtrip-" + $timestamp + ".wsb")

# Quote-safe arguments for the logon command.
$command = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "{0}" -IAmInAThrowawayMachine -RepoRoot "{1}" -OutputDir "{2}"' -f $launcher, $SandboxMountPath, $sandboxOutput
$escapedCommand = [System.Security.SecurityElement]::Escape($command)
$escapedHostPath = [System.Security.SecurityElement]::Escape($RepoRoot)
$escapedMountPath = [System.Security.SecurityElement]::Escape($SandboxMountPath)

$wsb = @"
<Configuration>
  <!-- Generated by tests\vm\New-SandboxConfig.ps1 on $(Get-Date -Format 'u') -->
  <!-- Runs tests\vm\Run-RoundTripTest.bat inside a disposable Windows Sandbox. -->
  <!-- Writes results back into the mapped repository folder: $escapedHostPath -->
  <VGpu>Disable</VGpu>
  <Networking>Enable</Networking>
  <MappedFolders>
    <MappedFolder>
      <HostFolder>$escapedHostPath</HostFolder>
      <SandboxFolder>$escapedMountPath</SandboxFolder>
      <ReadOnly>false</ReadOnly>
    </MappedFolder>
  </MappedFolders>
  <LogonCommand>
    <Command>$escapedCommand</Command>
  </LogonCommand>
</Configuration>
"@

Set-Content -LiteralPath $wsbPath -Value $wsb -Encoding UTF8

Write-Host ''
Write-Host 'Windows Sandbox round-trip config written.' -ForegroundColor Green
Write-Host ("  config  : {0}" -f $wsbPath)
Write-Host ("  results : {0}" -f (Join-Path $RepoRoot ("artifacts\sandbox-" + $timestamp)))
Write-Host ("  feature : {0}" -f $featureState)
Write-Host ''

if ($featureState -ne 'Enabled') {
    Write-Host 'Windows Sandbox is not enabled on this machine. Enable it once, then reboot:' -ForegroundColor Yellow
    Write-Host '  Enable-WindowsOptionalFeature -Online -FeatureName Containers-DisposableClientVM -All' -ForegroundColor Yellow
    Write-Host ''
    Write-Host 'Until then the .wsb is just a file - it will not launch a sandbox.' -ForegroundColor Yellow
    Write-Host ''
}

Write-Host 'Next: double-click the .wsb file.' -ForegroundColor Cyan
Write-Host 'The sandbox is disposable; the report is written into the mapped repository folder.'
